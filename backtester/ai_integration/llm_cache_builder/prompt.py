# ── Few-shot block builder ────────────────────────────────────────────────


def _build_few_shot_block() -> str:
    """Build the few-shot section by rendering example records through
    ``build_user_prompt()``.

    Called lazily so the input sections are always identical to what the
    real pipeline sends to the LLM — any spacing or field-order change in
    ``build_user_prompt()`` automatically propagates here.
    """
    ex1_input = build_user_prompt(_EX1_DATE, _EX1_RECORDS)
    ex2_input = build_user_prompt(_EX2_DATE, _EX2_RECORDS)
    return (
        "\n"
        "━━━ EXAMPLES ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n"
        "\n"
        "Study the two examples below before responding.\n"
        "Each shows the exact input format followed by the expected raw JSON output.\n"
        "\n"
        "── Example 1 of 2  (2 tickers — one vetoed for overheat) ───────────────\n"
        "Input:\n"
        f"{ex1_input}\n"
        "\n"
        "Output:\n"
        f"{_EX1_OUTPUT}\n"
        "\n"
        "── Example 2 of 2  (3 tickers — weak-signal veto, regime < 1.0) ────────\n"
        "Input:\n"
        f"{ex2_input}\n"
        "\n"
        "Output:\n"
        f"{_EX2_OUTPUT}\n"
        "\n"
        "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n"
        "Now respond to the next user message using the same format.\n"
    )


# ── Public API ────────────────────────────────────────────────────────────


@functools.lru_cache(maxsize=1)
def build_system_prompt() -> str:
    """Return the full system prompt: base instructions + few-shot examples.

    Result is cached after the first call — the function is pure and the
    examples are deterministic, so caching is safe.
    """
    return _SYSTEM_PROMPT_BASE + _build_few_shot_block()


# ── User prompt (per day) ─────────────────────────────────────────────────

# Feature keys we always show first, in this order.
_PRIORITY_FEATURE_KEYS: tuple[str, ...] = (
    "momentum_quality_score",
    "trend_quality_score",
    "range_recovery_bonus",
    "overheat_penalty",
    "pullback_exhaustion_penalty",
)


def build_user_prompt(
    date_key: str,
    day_records: list[dict[str, Any]],
) -> str:
    """Build the user-turn prompt for a single trading day.

    Parameters
    ----------
    date_key:
        ISO date string, e.g. ``"2024-01-15"``.
    day_records:
        List of JSONL records (all sharing ``date_key``).  Each record has
        at minimum ``ticker``, ``base_score``, ``features``, ``decision``,
        ``rule_gate_passed``, ``score_gate_passed``.
    """
    lines: list[str] = [
        f"Date: {date_key}",
        f"Candidates: {len(day_records)}",
        "",
    ]

    for rec in day_records:
        ticker = rec.get("ticker", "?")
        base = rec.get("base_score", 0.0)
        features: dict[str, Any] = rec.get("features") or {}
        decision = rec.get("decision", "unknown")
        rule_gate = rec.get("rule_gate_passed")
        score_gate = rec.get("score_gate_passed")

        lines.append(f"Ticker: {ticker}")
        lines.append(f"  base_score            {_fmt_float(base)}")
        lines.append(f"  decision              {decision}")
        lines.append(f"  rule_gate_passed      {rule_gate}")
        lines.append(f"  score_gate_passed     {score_gate}")

        # Priority features first, then any extras.
        emitted: set[str] = set()
        for key in _PRIORITY_FEATURE_KEYS:
            if key in features:
                lines.append(f"  {key:<30}  {_fmt_float(features[key])}")
                emitted.add(key)
        for key, val in features.items():
            if key not in emitted:
                try:
                    lines.append(f"  {key:<30}  {_fmt_float(val)}")
                except (TypeError, ValueError):
                    lines.append(f"  {key:<30}  {val!r}")

        lines.append("")

    tickers_csv = ", ".join(
        str(r.get("ticker", "?")) for r in day_records
    )
    lines.append(
        f"Provide signals for all {len(day_records)} ticker(s): {tickers_csv}"
    )
    return "\n".join(lines)


def _fmt_float(v: Any) -> str:
    try:
        return f"{float(v):.4f}"
    except (TypeError, ValueError):
        return str(v)


# ── Correction prompt ─────────────────────────────────────────────────────


def build_correction_prompt(error_description: str) -> str:
    """Build the follow-up user turn after a parse failure.

    Parameters
    ----------
    error_description:
        Human-readable description of what went wrong with the previous
        response (from ``ParseError``).
    """
    return (
        f"Your previous response could not be parsed.\n"
        f"Error: {error_description}\n\n"
        "Please provide a corrected response that is valid JSON matching the "
        "required schema exactly.\n"
        "— No markdown code fences.\n"
        "— No prose before or after the JSON.\n"
        "— Every ticker from the original request must be present.\n"
        "— Ranks must be unique integers starting from 1."
    )
