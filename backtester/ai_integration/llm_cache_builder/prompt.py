"""Prompt construction for the LLM batch cache generator.

Three public functions:

* ``build_system_prompt()``    — static system instructions + few-shot
                                  examples (called once, result cached).
* ``build_user_prompt()``      — per-day user turn with ticker features.
* ``build_correction_prompt()``— follow-up turn after a parse failure.

Few-shot examples
-----------------
Two concrete input→output demonstrations are appended to the system
prompt.  They are generated by calling ``build_user_prompt()`` on fixed
example records, so the input sections are *always* byte-for-byte
identical to what the real pipeline produces — any format change
automatically propagates to the examples.

The example output strings are hardcoded JSON that passes
``parse_response()`` validation.  They cover two key failure modes that
models tend to mis-handle:

  Example 1 (2 tickers) — veto=true with required reason + confidence.
    Reinforces: raw JSON only, veto fields must all be set together.

  Example 2 (3 tickers) — weak-signal veto, regime < 1.0, correct ranks.
    Reinforces: all tickers present, unique ranks, regime below neutral.
"""
from __future__ import annotations

import functools
from typing import Any


# ── System prompt (base) ──────────────────────────────────────────────────

_SYSTEM_PROMPT_BASE = """\
You are an expert quantitative analyst specialising in Korean equity momentum \
strategies.

Your task: given a batch of candidate stock features for a single trading day, \
produce structured JSON trading signals consumed by an automated backtest engine.

━━━ FEATURE GLOSSARY ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

base_score
    Raw momentum selection score (typically 1.0–5.0). Higher = stronger candidate.

momentum_quality_score  [0–1]
    Quality of recent short-term price momentum.
    ≥ 0.50 = healthy momentum    < 0.20 = weak or absent

trend_quality_score  [0–1]
    Alignment of price action with the medium-term trend.
    ≥ 0.50 = trend-aligned       < 0.20 = counter-trend or ranging

range_recovery_bonus  [0–1]
    Intraday recovery off the session low (demand signal).
    ≥ 0.30 = strong intraday demand

overheat_penalty  [0–1]
    Overbought / extension risk — price has run too far too fast.
    > 0.25 = extended; candidate at risk of mean-reversion

pullback_exhaustion_penalty  [0–1]
    Stalled pullback with no follow-through buying — momentum fading.
    > 0.20 = exhausted; upside limited

decision          Engine pre-filter verdict: "approved" or "rejected"
rule_gate_passed  All rule-based filters cleared (bool)
score_gate_passed Scored above entry threshold (bool)

━━━ OUTPUT FORMAT ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Respond with a single raw JSON object — no markdown fences, no prose before or \
after:

{
  "regime_multiplier": <float, 0.80–1.20>,
  "tickers": {
    "<TICKER>": {
      "delta":           <float, -5.0 to +5.0>,
      "veto":            <bool>,
      "veto_confidence": <float, 0.0–1.0>,
      "veto_reason":     <null | "overheat" | "pullback_exhaustion" | "weak_signal" | "regime_risk" | "other">,
      "rank":            <int, unique, 1 = highest quality>
    }
  }
}

━━━ SIGNAL SEMANTICS ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

regime_multiplier
    Market-wide quality this session.
    0.80 = poor conditions, reduce position sizing
    1.00 = neutral
    1.20 = excellent conditions, full sizing

delta  [-5, +5]
    Additive adjustment to the engine's selection score.
    Positive values increase the chance this ticker is selected today.
    Negative values suppress it.  Zero = no opinion.

veto  [bool]
    True blocks the ticker from selection regardless of engine score.
    Use sparingly — only when you have high confidence in a near-term loss.

veto_confidence  [0–1]
    Confidence in the veto.  Required > 0.0 when veto = true.
    When veto = false, use to signal residual concern (0.0 = none).

veto_reason
    Categorical cause when veto = true; null otherwise.

rank  [1 .. N]
    Relative ranking of candidates for today. 1 = strongest, N = weakest.
    Ranks must be unique integers; gaps will be renormalised automatically.

━━━ RULES ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

1. Include EVERY ticker from the input — no omissions.
2. Ranks must be unique integers starting from 1.
3. When veto = true you MUST set veto_confidence > 0.0 AND a non-null veto_reason.
4. Respond with raw JSON only.  No code fences.  No commentary.
"""


